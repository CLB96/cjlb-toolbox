const DICCIONARIOS: Record<'es' | 'en', Record<GageflowKey, string>> = { es, en }

/** Diccionarios completos, para el export (PNG/PDF) que no puede usar hooks. */
export const TEXTOS = DICCIONARIOS

const ERROR_FORM: Record<string, GageflowKey> = {
  requerido: 'errRequerido',
  muyLargo: 'errMuyLargo',
  noNumerico: 'errNoNumerico',
  fueraDeRango: 'errFueraDeRango',
  lslMayorUsl: 'errLslMayorUsl',
  nominalFuera: 'errNominalFuera',
  duplicado: 'errDuplicado',
  resolucionGruesa: 'errResolucionGruesa',
  toleranciaIncompleta: 'errToleranciaIncompleta',
  sinOperadores: 'errSinOperadores',
}

export function useGageflowT(): (key: GageflowKey, vars?: Vars) => string {
  const { lang } = useI18n()
  const dic = DICCIONARIOS[lang]
  return (key, vars) =>
    dic[key].replace(/\{(\w+)\}/g, (m, name: string) => (vars && name in vars ? String(vars[name]) : m))
}

export function errorFormTexto(codigo: string): GageflowKey {
  return ERROR_FORM[codigo] ?? 'errRequerido'
}
