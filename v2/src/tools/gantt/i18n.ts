export type GanttKey = keyof typeof es
type Entry = string | ((...args: A[]) => string) | Record<string, string>

export const GANTT_I18N: Record<Lang, Record<GanttKey, Entry>> = { es, en }

/** T() del original: idioma -> ES -> clave; las entradas función reciben los argumentos. */
export function translate(lang: Lang, key: GanttKey, ...args: A[]): string {
  const v: Entry | undefined = GANTT_I18N[lang]?.[key] ?? GANTT_I18N.es[key]
  if (typeof v === 'function') return v(...args)
  if (typeof v === 'string') return v
  return key
}

/** Entradas objeto del diccionario (pieDesc). */
export function translateMap(lang: Lang, key: 'pieDesc'): Record<string, string> {
  return (GANTT_I18N[lang]?.[key] ?? GANTT_I18N.es[key]) as Record<string, string>
}

export type GanttT = (key: GanttKey, ...args: A[]) => string

/** Traductor de Gantt con el idioma del toolbox. */
export function useGanttT(): { t: GanttT; lang: Lang } {
  const { lang } = useI18n()
  return { t: (key, ...args) => translate(lang, key, ...args), lang }
}

