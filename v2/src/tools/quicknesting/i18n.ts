export const DICTIONARIES: Record<'es' | 'en', Record<QnKey, string>> = { es, en }

export type Vars = Record<string, string | number>

/** Igual que `text()` del original: un marcador sin valor se muestra como «—». */
export function qnText(lang: 'es' | 'en', key: QnKey, vars: Vars = {}): string {
  const template = DICTIONARIES[lang][key] ?? DICTIONARIES.es[key]
  return template.replace(/\{(\w+)\}/g, (_m, name: string) => (name in vars ? String(vars[name]) : '—'))
}

export function useQnT(): (key: QnKey, vars?: Vars) => string {
  const { lang } = useI18n()
  return (key, vars) => qnText(lang, key, vars)
}

export function isQnKey(key: string): key is QnKey {
  return key in es
}
